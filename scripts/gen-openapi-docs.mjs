#!/usr/bin/env node
/**
 * gen-openapi-docs: regenerate content/docs/api/rest/reference/ (one page per
 * endpoint) and content/docs/api/rest/commands.mdx (a hand-built catalog of
 * every command in the Command union) from the vendored openapi/rest-api.json.
 *
 * Pure function of the vendored file — no network access, no private repo
 * involved. This is what CI runs to catch drift: if someone hand-edits a
 * generated page, or updates openapi/rest-api.json without regenerating,
 * `git diff --exit-code -- content/docs/api/rest` after this script fails.
 *
 * This script does NOT know whether openapi/rest-api.json itself is stale
 * relative to its source — see openapi/README.md for that gap.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createOpenAPI } from 'fumadocs-openapi/server';
import { generateFiles } from 'fumadocs-openapi';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const vendoredPath = join(root, 'openapi', 'rest-api.json');
const restDir = join(root, 'content', 'docs', 'api', 'rest');
const referenceDir = join(restDir, 'reference');
const commandsPath = join(restDir, 'commands.mdx');

if (!existsSync(vendoredPath)) {
  console.error(
    `No vendored spec at ${vendoredPath}. Run scripts/sync-openapi.mjs first (see openapi/README.md).`,
  );
  process.exit(1);
}

const doc = JSON.parse(readFileSync(vendoredPath, 'utf8'));

// ---------------------------------------------------------------------------
// 1. Per-endpoint pages, generated by fumadocs-openapi.
// ---------------------------------------------------------------------------

const openapi = createOpenAPI({ input: ['./openapi/rest-api.json'] });

// camelCase operationId -> kebab-case filename, matching this site's
// existing page-naming convention (see content/docs/reference/functions/).
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

await generateFiles({
  input: openapi,
  output: referenceDir,
  per: 'operation',
  groupBy: 'none',
  // The default namer uses the raw (camelCase) operationId for operation
  // pages — slugify isn't consulted there. Kebab-case explicitly to match
  // this site's existing page-naming convention.
  name(output, document) {
    if (output.type === 'operation') {
      const operation = document.paths[output.item.path][output.item.method];
      return kebab(operation.operationId ?? `${output.item.method}-${output.item.path}`);
    }
    return kebab(output.item.name ?? 'page');
  },
  meta: true,
  addGeneratedComment:
    'This file was generated from openapi/rest-api.json by scripts/gen-openapi-docs.mjs. Do not edit directly — see openapi/README.md.',
  // seoDescription needs a hand-tuned 150-160 char summary per operation
  // (see how enrichment/*.yaml does it for function pages) — not attempted
  // here, so these generated pages are missing that one AEO signal. seoTitle
  // and llmsDescription are safe to derive automatically.
  frontmatter(title) {
    return {
      seoTitle: `${title} — TrueCalc REST API`,
      llmsDescription: `TrueCalc REST API: ${title}. Pre-release — see /api/rest for deployment and auth status.`,
    };
  },
});

// ---------------------------------------------------------------------------
// 2. Commands catalog: POST /workbooks/{id}/commands takes a `commands` array
// where each entry is one of 61 discriminated-union members. That union IS
// the write surface, so it needs to be individually browsable as names +
// one-line descriptions here, in addition to the full field-level schema
// (with a variant selector) on the generated /reference/post-commands page.
// ---------------------------------------------------------------------------

const schemas = doc.components?.schemas ?? {};
const command = schemas.Command;
if (!command?.oneOf) {
  console.error('components.schemas.Command.oneOf not found in the vendored spec — cannot build the commands catalog.');
  process.exit(1);
}

const CATEGORY_LABELS = {
  chart: 'Charts',
  clipboard: 'Clipboard',
  edit: 'Edit',
  format: 'Format',
  structure: 'Structure',
  data: 'Data',
  file: 'File',
  read: 'Read',
  sheet: 'Sheet',
  view: 'View',
};

const categories = new Map(); // category -> [{ type, description, extraRequired }]

for (const entry of command.oneOf) {
  const name = entry.$ref.split('/').pop();
  const schema = schemas[name];
  if (!schema) continue;

  const type = schema.properties?.type?.const ?? name;
  const category = type.includes(':') ? type.split(':')[0] : 'other';
  const description = (schema.description ?? '').trim();
  const required = new Set(schema.required ?? []);
  ['commandId', 'sheet', 'type'].forEach((f) => required.delete(f));

  if (!categories.has(category)) categories.set(category, []);
  categories.get(category).push({ type, description, extraRequired: [...required] });
}

const mdxEscape = (text) =>
  String(text).replaceAll('{', '&#123;').replaceAll('}', '&#125;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');

const lines = [
  '---',
  'title: Commands',
  'description: All commands accepted by POST /workbooks/{id}/commands, grouped by category.',
  `seoTitle: "TrueCalc REST API Commands — All ${command.oneOf.length} Command Types"`,
  `seoDescription: "All ${command.oneOf.length} commands TrueCalc's REST API accepts in POST /workbooks/{id}/commands, grouped by category: edit, format, structure, data, charts, sheets, and more."`,
  `llmsDescription: "Catalog of all ${command.oneOf.length} commands accepted by the TrueCalc REST API's command endpoint (POST /workbooks/{id}/commands), grouped by category with each command's required fields."`,
  '---',
  '',
  `{/* Generated from openapi/rest-api.json by scripts/gen-openapi-docs.mjs. Do not edit directly — see openapi/README.md. */}`,
  '',
  `Every entry in a \`POST /workbooks/{id}/commands\` batch is one of these ${command.oneOf.length} commands, chosen by its \`type\`. This page lists them all by name so the union isn't a single opaque blob; for the exact field-level schema of any one command (including validation rules), open [the commands endpoint reference](/api/rest/reference/post-commands) and pick it from the request-body schema selector — the \`type\` value below (e.g. \`edit:setCell\`) is what to look for there.`,
  '',
];

for (const [category, commands] of categories) {
  const label = CATEGORY_LABELS[category] ?? category;
  lines.push(`## ${label}`, '');
  for (const { type, description, extraRequired } of commands) {
    lines.push(`### \`${type}\``, '');
    if (description) lines.push(mdxEscape(description), '');
    if (extraRequired.length > 0) {
      lines.push(`Required fields beyond \`commandId\`, \`sheet\`, \`type\`: ${extraRequired.map((f) => `\`${f}\``).join(', ')}.`, '');
    } else {
      lines.push('No required fields beyond `commandId`, `sheet`, `type`.', '');
    }
  }
}

writeFileSync(commandsPath, lines.join('\n'));

// ---------------------------------------------------------------------------
// 3. Nav: content/docs/api/rest/meta.json fixes the page order; the
// generated reference/meta.json (written by generateFiles above) fixes
// per-operation order within that subsection.
// ---------------------------------------------------------------------------

const restMetaPath = join(restDir, 'meta.json');
writeFileSync(
  restMetaPath,
  JSON.stringify({ title: 'REST', pages: ['index', 'commands', 'reference'] }, null, 2) + '\n',
);

console.log(`Wrote ${categories.size} categories / ${command.oneOf.length} commands to ${commandsPath}`);
console.log(`Wrote endpoint pages to ${referenceDir}`);
